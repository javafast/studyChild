/* 语文识字每学完三课，自动插入一关综合复习。words 保留原始词条，
   进入关卡时由 app.js 重新打乱，确保每次复习顺序都不一样。 */
TRACKS.forEach((track) => {
  if (!/^chinese\d*$/.test(track.id)) return;
  const lessons = track.chapters.slice();
  const chapters = [];
  lessons.forEach((chapter, index) => {
    chapters.push(chapter);
    if ((index + 1) % 3 !== 0) return;
    chapters.push({
      id: track.id + "-review-" + ((index + 1) / 3),
      name: "复习关 · 前三课",
      tip: "前三课的生字已经打乱，再完整输入一次吧！",
      isReview: true,
      words: lessons.slice(index - 2, index + 1).flatMap((lesson) => lesson.words)
    });
  });
  track.chapters = chapters;
});
